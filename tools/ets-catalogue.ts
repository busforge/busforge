export const SWEEP_MASKS = ["07B0", "0701", "0705"];
export const GENERATED_START = "<!-- generated by tools/ets-catalogue.ts list: do not edit below -->";
export const GENERATED_END = "<!-- end of the generated part -->";

// ---- ETS's files ----

interface Translation { Language: string; Translation: { ApplicationProgramName?: string | null } }
export interface IndexEntry {
  Id: string; ApplicationIdentifier: number[]; FingerPrint: number; OrderNumber: string; MediumTypeIds: string[];
  ApplicationProgramName: string; Translations?: Translation[]; SecurityInfo: number; NoDownloadWithoutPlugin: boolean;
  RequiresExternalSoftware: boolean; DownloadInfoIncomplete: boolean;
}
export interface IndexFile {
  ManufacturerId: number; ManufacturerName: string; Version: number; Entries: IndexEntry[];
  Markets?: { Id: string; DefaultName: string; CatalogIds: string[] }[];
}
export interface MarketFile { Version: number; Markets: { Id: string; DefaultName: string }[] }
// An application's element in ETS's product store, by attribute.
export type ApplicationHeader = Record<string, string>;
export interface Source { ets: string; licence: string; catalogueDate: string; fetched: string }
export interface Fetched {
  indexes: IndexFile[]; market: MarketFile; applications: Map<string, ApplicationHeader>; source: Source;
  // The store's catalogue items by itemKey of their id: the hardware-to-programs they name (one, unless the store
  // holds the item twice); each hardware-to-program's program lists (one, unless the store holds it twice).
  items: Map<string, string[]>; programs: Map<string, string[][]>;
}

const json = <T>(text: string): T => JSON.parse(text.replace(/^\uFEFF/, "")) as T;

// The attributes of one XML start tag.
export function attributes(tag: string): ApplicationHeader {
  const out: ApplicationHeader = {};
  for (const m of tag.matchAll(/([A-Za-z_][\w.-]*)="([^"]*)"/g)) out[m[1]] = xmlUnescape(m[2]);
  return out;
}

// ---- fetch ----

function fetchCatalogue(out: string): void {
  const h = host();
  const store = h.data;
  if (existsSync(out) && readdirSync(out).length) throw new Error(`${out} exists and is not empty`);
  mkdirSync(out, { recursive: true });
  const tar = ssh(`cd ${q(`${store}/OC`)} && tar czf - IndexFiles/*.idx MarketFile/MarketFile.mf`, "", { timeoutMs: 300_000 });
  execFileSync("tar", ["xzf", "-", "-C", out], { input: tar });
  // One line per application in the store: its directory and its <AP …> start tag (empty where none reads).
  const aps = ssh(`cd ${q(`${store}/ProductStore`)} && for f in M-*/M-*_A-*/A; do [ -e "$f" ] || continue; printf '%s\\t' "$f"; grep -a -m1 -o '<AP [^>]*>' "$f" || echo; done`, "", { timeoutMs: 900_000 });
  writeFileSync(join(out, "applications.tsv"), aps);
  // The store's catalogue items and hardware-to-programs, as grep prints them (`<file>:<element>`); grep's 1 (no
  // match in a file) passes, its 2 (a file it cannot read) fails the fetch.
  const elements = (file: string, pattern: string) => ssh(`cd ${q(`${store}/ProductStore`)} && for f in M-*/${file}; do [ -e "$f" ] || continue; grep -a -H -o -E ${q(pattern)} "$f"; [ $? -le 1 ] || exit 2; done`, "", { timeoutMs: 900_000 });
  writeFileSync(join(out, "catalogue-items.txt"), elements("C", "<CITEM [^>]*>"));
  writeFileSync(join(out, "programs.txt"), elements("H", "<H2P [^>]*>|</H2P>|<APR [^>]*>"));
  // ETS6.log and its rotations, oldest first (ETS6.log.<n> is older the higher its n).
  // Each fact on a line of its own, named, so one that is missing leaves the others in place.
  const said = ssh("bash -s", `cd ${q(store)}/OC/IndexFiles && echo "date=$(date -u -r "$(ls -t *.idx | head -1)" '+%Y-%m-%dT%H:%M:%SZ')"
cd ${q(h.etsLog)} && logs=$(ls ETS6.log ETS6.log.* 2>/dev/null | sort -t. -k3,3nr) && [ -n "$logs" ] || exit 1
echo "ets=$(cat $logs | grep -a 'StartupLogging - Version:' | tail -1 | sed 's/.*Version: //' | tr -d '\r')"
echo "licence=$(cat $logs | grep -a -o 'LICENSE="[^"]*"' | tail -1 | sed 's/^LICENSE="//; s/"$//')"`, { timeoutMs: 120_000 }).toString("latin1");
  const fact = (name: string) => said.match(new RegExp(`^${name}=(.+)$`, "m"))?.[1].trim() ?? "";
  const source: Source = { catalogueDate: fact("date"), ets: fact("ets"), licence: fact("licence"), fetched: new Date().toISOString() };
  if (!source.catalogueDate || !source.ets || !source.licence) throw new Error(`the bench host names no catalogue date, ETS version or licence: ${said.trim()}`);
  writeFileSync(join(out, "source.json"), `${JSON.stringify(source, null, 1)}\n`);
  const n = readdirSync(join(out, "IndexFiles")).length, a = aps.toString().split("\n").filter(Boolean).length;
  console.log(`${out}: ${n} index files, ${a} applications in ETS's product store`);
}

export function readFetched(dir: string): Fetched {
  const indexes = readdirSync(join(dir, "IndexFiles")).filter((f) => f.endsWith(".idx")).sort((a, b) => parseInt(a) - parseInt(b))
    .map((f) => json<IndexFile>(readFileSync(join(dir, "IndexFiles", f), "utf8")));
  const applications = new Map<string, ApplicationHeader>();
  for (const line of readFileSync(join(dir, "applications.tsv"), "utf8").split("\n")) {
    if (!line) continue;
    const tab = line.indexOf("\t");
    if (tab < 1) throw new Error(`applications.tsv holds a line without a path: ${line.slice(0, 120)}`);
    const path = line.slice(0, tab), tag = line.slice(tab + 1);
    const id = path.split("/")[1];
    if (!tag?.trim()) throw new Error(`${path} in ETS's product store holds no <AP> element`);
    const a = attributes(tag);
    if (a.Id !== id) throw new Error(`${path} in ETS's product store holds application ${a.Id}`);
    applications.set(id, a);
  }
  const lines = (name: string) => {
    if (!existsSync(join(dir, name))) throw new Error(`${dir} holds no ${name}: fetch it again`);
    return readFileSync(join(dir, name), "utf8").split("\n").filter(Boolean).map((l) => ({ file: l.slice(0, l.indexOf(":")), tag: l.slice(l.indexOf(":") + 1), line: l }));
  };
  const add = <T>(m: Map<string, T[]>, k: string, v: T, same: (a: T, b: T) => boolean) => {
    const vs = m.get(k) ?? [];
    if (!vs.some((x) => same(x, v))) vs.push(v);
    m.set(k, vs);
  };
  const items = new Map<string, string[]>();
  for (const { tag, line } of lines("catalogue-items.txt")) {
    const a = attributes(tag);
    if (!a.Id || !a.Hardware2ProgramRefId) throw new Error(`catalogue-items.txt holds a catalogue item without its id or hardware-to-program: ${line.slice(0, 160)}`);
    add(items, itemKey(a.Id), a.Hardware2ProgramRefId, (x, y) => x === y);
  }
  // Each <APR> belongs to the <H2P> open around it in the same file.
  const programs = new Map<string, string[][]>();
  let open: { file: string; id: string; refs: string[] } | null = null;
  const close = () => { if (open) add(programs, open.id, open.refs, (x, y) => x.join() === y.join()); open = null; };
  for (const { file, tag, line } of lines("programs.txt")) {
    if (tag.startsWith("</H2P")) { if (open?.file !== file) throw new Error(`programs.txt closes a hardware-to-program it did not open: ${line.slice(0, 160)}`); close(); continue; }
    const a = attributes(tag);
    if (tag.startsWith("<H2P ")) {
      if (open) throw new Error(`programs.txt opens a hardware-to-program inside ${open.id}: ${line.slice(0, 160)}`);
      if (!a.Id) throw new Error(`programs.txt holds a hardware-to-program without its id: ${line.slice(0, 160)}`);
      open = { file, id: a.Id, refs: [] };
      if (tag.endsWith("/>")) close();
      continue;
    }
    if (!a.RefId || open?.file !== file) throw new Error(`programs.txt holds a program reference outside a hardware-to-program: ${line.slice(0, 160)}`);
    open.refs.push(a.RefId);
  }
  if (open) throw new Error(`programs.txt ends inside hardware-to-program ${(open as { id: string }).id}`);
  return {
    indexes, market: json<MarketFile>(readFileSync(join(dir, "MarketFile", "MarketFile.mf"), "utf8")), applications,
    source: json<Source>(readFileSync(join(dir, "source.json"), "utf8")), items, programs,
  };
}

// A catalogue item's id without its programs' hashes: the index and ETS's store name one item with their own
// (`…_HP-0003-32-CB68_CI-…` and `…_HP-0003-32-73C9_CI-…`).
export const itemKey = (id: string) => id.replace(/_HP-[^_]*(?=_CI-)/, (hp) => hp.replace(/([0-9A-F]{4}-[0-9A-F]{2})-[0-9A-F]{4}/g, "$1"));

// ---- the list ----

export interface Row {
  // The application as ETS's product store holds it; the index's ids of it where they differ.
  application: string; catalogueApplications?: string[]; manufacturer: string; manufacturerName: string; mask: string; version: string; name: string;
  // The order number the sweep searches the catalogue for, and every order number the market offers it under.
  orderNumber: string; orderNumbers: string[]; catalogueEntries: number;
  // Other applications under one of its order numbers at its version (any mask). noOwnOrderNumber: no order
  // number the driver can search for it by, as each one (compared as the driver compares them) lists more than
  // one catalogue row at its version, another application's or its own again.
  sameOrderAndVersion?: { orderNumber: string; applications: string[] }[]; noOwnOrderNumber?: true;
  // The hardware's second program beside the application, its type from the product data (null: not loaded).
  secondProgram?: { application: string; programType: string | null }[];
  secure?: true; pluginRequired?: true; externalSoftware?: true; downloadInfoIncomplete?: true;
}
// A difference to bussard's manifest: its reason (one of a few, counted in the Markdown) and what it names.
export interface BussardDifference { application: string; mask: string; reason: string; detail?: string; outcome?: string }
export interface BussardCheck {
  generated: string; theirs: number; ours: number; both: number;
  theirsNotOurs: BussardDifference[]; oursNotTheirs: BussardDifference[]; maskDiffers: { application: string; ours: string; theirs: string }[];
}
export interface CatalogueList {
  format: string; source: Source & { market: string; indexFiles: number; masks: string[] };
  counts: {
    // applications = loaded + unloaded + refusedApplications.
    indexEntries: number; marketEntries: number; withoutApplication: number; refusedEntries: number;
    applications: number; loaded: number; unloaded: number; refusedApplications: number;
    byMask: Record<string, number>; rows: number; rowsByManufacturer: Record<string, Record<string, number>>; sameOrderAndVersion: number;
    // Catalogue ids of the market that name no entry of the index; second programs that are applications.
    marketIdsWithoutEntry: number; secondApplications: number;
  };
  rows: Row[];
  unloaded: { application: string; orderNumbers: string[] }[];
  // An index entry whose parts disagree (no application counted), an application or a second program whose
  // product data does not fit it.
  refused: { kind: "entry" | "application" | "second program"; entry: string; why: string }[];
  bussard?: BussardCheck;
}

const hex = (n: number, digits: number) => n.toString(16).toUpperCase().padStart(digits, "0");
const PROGRAM = "([0-9A-F]{4})-([0-9A-F]{2})-([0-9A-F]{4})((?:-O[0-9A-F]+)?)";
// An entry's hardware-to-program part names its application and, where the hardware has one, a second program
// (a PEI program, or a second application).
const ENTRY_APPLICATION = new RegExp(`^(M-[0-9A-F]{4})_H-.*_HP-${PROGRAM}(?:-${PROGRAM})?_CI-`);
const ENTRY_WITHOUT_APPLICATION = /_HP_CI-/;

// The application an entry carries, checked against its application identifier and fingerprint; null for an
// entry without one; a string for an entry whose parts disagree.
function entryApplication(e: IndexEntry, manufacturerId: number): { id: string; manufacturer: string; version: number; second?: string } | null | string {
  if (ENTRY_WITHOUT_APPLICATION.test(e.Id)) return null;
  const m = e.Id.match(ENTRY_APPLICATION);
  if (!m) return "its id names no application";
  const [, manufacturer, number, version, fingerprint, suffix, ...second] = m;
  if (manufacturer !== `M-${hex(manufacturerId, 4)}`) return `it stands in manufacturer M-${hex(manufacturerId, 4)}'s index`;
  if (!Number.isInteger(e.FingerPrint)) return `its fingerprint is ${JSON.stringify(e.FingerPrint)}`;
  const ai = e.ApplicationIdentifier;
  const fromIdentifier = ai?.length === 5 ? `M-${hex(ai[0] * 256 + ai[1], 4)}_A-${hex(ai[2] * 256 + ai[3], 4)}-${hex(ai[4], 2)}` : "";
  if (fromIdentifier !== `${manufacturer}_A-${number}-${version}`) return `its application identifier [${ai?.join(",")}] is no ${manufacturer}_A-${number}-${version}`;
  if (hex(e.FingerPrint, 4) !== fingerprint) return `its fingerprint ${hex(e.FingerPrint, 4)} is not the id's ${fingerprint}`;
  const id = `${manufacturer}_A-${number}-${version}-${fingerprint}${suffix}`;
  return { id, manufacturer, version: parseInt(version, 16), ...(second[0] ? { second: `${manufacturer}_A-${second[0]}-${second[1]}-${second[2]}${second[3]}` } : {}) };
}

const germanName = (e: IndexEntry) => e.Translations?.find((t) => t.Language === "de-DE")?.Translation.ApplicationProgramName ?? e.ApplicationProgramName;
const byText = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0);

// Why ETS's product data for program `id` does not name it (its number and version), or null.
function headerMismatch(id: string, h: ApplicationHeader): string | null {
  const [, number, version] = id.match(/_A-([0-9A-F]{4})-([0-9A-F]{2})/)!;
  const is = (v: string | undefined, n: string) => v !== undefined && /^\d+$/.test(v) && Number(v) === parseInt(n, 16);
  return is(h.ApplicationNumber, number) && is(h.ApplicationVersion, version)
    ? null : `ETS's product data names application number ${h.ApplicationNumber} version ${h.ApplicationVersion}`;
}

// An application as the index names it: its catalogue entries and second programs.
interface Named { id: string; manufacturer: string; manufacturerName: string; version: number; name: string; second: Set<string>; entries: IndexEntry[] }

// A program's id without its hash: M-0001_A-0003-32 for M-0001_A-0003-32-73C9, M-0002_A-4758-11-O0007 for
// M-0002_A-4758-11-0055-O0007.
const withoutHash = (id: string) => id.replace(/-[0-9A-F]{4}(?=(-O[0-9A-F]+)?$)/, "");

// The programs ETS's product store holds for an application the index names, the application first: its catalogue
// items' hardware-to-programs, the program at the index's number, version and OEM being the application (its hash
// can differ from the index's), the others its second programs. null where the store holds none of its catalogue
// items; a refusal where the store's data is ambiguous or names no such program.
function storeApplication(f: Fetched, n: Named): { programs: string[] } | { refused: string } | null {
  const applications = new Set<string>(), seconds = new Set<string>();
  for (const e of n.entries) {
    const h2ps = f.items.get(itemKey(e.Id));
    if (!h2ps) continue;
    if (h2ps.length > 1) return { refused: `ETS's product store holds catalogue item ${e.Id} with several hardware-to-programs: ${h2ps.join(", ")}` };
    const lists = f.programs.get(h2ps[0]);
    if (!lists) return { refused: `ETS's product store holds no hardware-to-program ${h2ps[0]}` };
    if (lists.length > 1) return { refused: `ETS's product store holds hardware-to-program ${h2ps[0]} twice, with different programs` };
    const at = lists[0].filter((p) => withoutHash(p) === withoutHash(n.id));
    if (at.length !== 1) return { refused: `hardware-to-program ${h2ps[0]} in ETS's product store names ${at.length ? `${at.length} programs` : "no program"} at ${withoutHash(n.id)}` };
    applications.add(at[0]);
    for (const p of lists[0]) if (p !== at[0]) seconds.add(p);
  }
  if (applications.size > 1) return { refused: `its catalogue items name several applications in ETS's product store: ${[...applications].sort(byText).join(", ")}` };
  return applications.size ? { programs: [[...applications][0], ...[...seconds].sort(byText)] } : null;
}

export function catalogueList(f: Fetched, marketName: string, masks: string[], bussard?: BussardManifest): CatalogueList {
  const market = f.market.Markets.find((m) => m.DefaultName === marketName) ?? (() => { throw new Error(`ETS's market file holds no market ${marketName}`); })();
  const refused: CatalogueList["refused"] = [];
  let indexEntries = 0, marketEntries = 0, withoutApplication = 0, marketIdsWithoutEntry = 0;
  const named = new Map<string, Named>();
  for (const file of f.indexes) {
    const offered = new Set(file.Markets?.find((m) => m.Id === market.Id)?.CatalogIds ?? []);
    const ids = new Set(file.Entries.map((e) => e.Id));
    marketIdsWithoutEntry += [...offered].filter((id) => !ids.has(id)).length;
    for (const e of file.Entries) {
      indexEntries++;
      if (!offered.has(e.Id)) continue;
      marketEntries++;
      const a = entryApplication(e, file.ManufacturerId);
      if (a === null) { withoutApplication++; continue; }
      if (typeof a === "string") { refused.push({ kind: "entry", entry: e.Id, why: a }); continue; }
      const n = named.get(a.id) ?? { id: a.id, manufacturer: a.manufacturer, manufacturerName: file.ManufacturerName, version: a.version, name: germanName(e), second: new Set(), entries: [] };
      n.entries.push(e);
      if (a.second) n.second.add(a.second);
      named.set(a.id, n);
    }
  }
  // The applications by the id ETS's store holds them under: an application the index names under two hashes that
  // the store holds as one is one application. One the store holds no catalogue item of stands by the index's id.
  // catalogueIds: the index's ids of it; second / catalogueSecond: its second programs in the store and the index.
  interface App extends Named { catalogueIds: string[]; catalogueSecond: Set<string> }
  const apps = new Map<string, App>();
  const refuse = (id: string, why: string) => refused.push({ kind: "application", entry: id, why });
  for (const n of named.values()) {
    const held = storeApplication(f, n);
    if (held && "refused" in held) { refuse(n.id, held.refused); continue; }
    const [id, ...second] = held ? held.programs : [n.id, ...n.second];
    const app = apps.get(id) ?? { ...n, id, entries: [], second: new Set(), catalogueIds: [], catalogueSecond: new Set() };
    app.entries.push(...n.entries);
    app.catalogueIds.push(n.id);
    for (const s of second) app.second.add(s);
    for (const s of n.second) app.catalogueSecond.add(s);
    apps.set(id, app);
  }
  // The mask from the product data, checked against the application it names.
  const maskOf = new Map<string, string>();
  for (const app of apps.values()) {
    const h = f.applications.get(app.id);
    if (!h) continue;
    const mismatch = headerMismatch(app.id, h);
    if (mismatch) { refuse(app.id, mismatch); continue; }
    if (h.ProgramType !== "ApplicationProgram") { refuse(app.id, `ETS's product data holds it as ${h.ProgramType ?? "no program type"}`); continue; }
    // A mask with an extension (MV-0300-01000001…) is a mask too, never one of the sweep's.
    const m = h.MaskVersion?.match(/^MV-([0-9A-F]{4}(?:-[0-9A-F]+)?)$/);
    if (!m) { refuse(app.id, `ETS's product data holds no mask (MaskVersion ${h.MaskVersion ?? "missing"})`); continue; }
    maskOf.set(app.id, m[1]);
  }
  // The second programs' type from the product data (null: not loaded); one whose data names another program refused.
  const secondType = new Map<string, string | null>();
  for (const app of apps.values()) for (const id of app.second) {
    if (secondType.has(id)) continue;
    const h = f.applications.get(id), mismatch = h && headerMismatch(id, h);
    if (mismatch) refused.push({ kind: "second program", entry: id, why: mismatch });
    secondType.set(id, h && !mismatch ? h.ProgramType ?? null : null);
  }
  // Applications and catalogue rows under one order number at one version, over every application of the market:
  // the driver searches the whole catalogue by order number, compared by orderNumberKey.
  const atOrder = new Map<string, Set<string>>(), rowsAt = new Map<string, number>();
  const orderAt = (orderNumber: string, version: number) => `${orderNumberKey(orderNumber)}\t${version}`;
  for (const app of apps.values()) for (const e of app.entries) {
    const k = orderAt(e.OrderNumber, app.version);
    atOrder.set(k, (atOrder.get(k) ?? new Set()).add(app.id));
    rowsAt.set(k, (rowsAt.get(k) ?? 0) + 1);
  }
  const byMask: Record<string, number> = {};
  const rows: Row[] = [];
  const catalogueIdsOf = new Map<Row, string[]>();
  const unloaded: CatalogueList["unloaded"] = [];
  const isRefused = (app: App) => refused.some((r) => r.kind === "application" && r.entry === app.id);
  const orderNumbersOf = (app: App) => [...new Set(app.entries.map((e) => e.OrderNumber))].sort(byText);
  for (const app of [...apps.values()].sort((a, b) => byText(a.id, b.id))) {
    const mask = maskOf.get(app.id);
    if (!mask) {
      if (!isRefused(app)) unloaded.push({ application: app.id, orderNumbers: orderNumbersOf(app) });
      continue;
    }
    byMask[mask] = (byMask[mask] ?? 0) + 1;
    if (!masks.includes(mask)) continue;
    const orderNumbers = orderNumbersOf(app);
    const others = orderNumbers.map((o) => ({ orderNumber: o, applications: [...atOrder.get(orderAt(o, app.version))!].filter((x) => x !== app.id).sort(byText) }));
    const shared = others.filter((o) => o.applications.length);
    // An order number of its own: one catalogue row at the version (the driver refuses two, even of one
    // application); an order number of nothing but spaces is none to search for.
    const searchable = (o: { orderNumber: string }) => orderNumberKey(o.orderNumber) !== "";
    const own = others.find((o) => searchable(o) && rowsAt.get(orderAt(o.orderNumber, app.version)) === 1);
    const elsewhere = app.catalogueIds.filter((id) => id !== app.id).sort(byText);
    const row: Row = {
      application: app.id, ...(elsewhere.length ? { catalogueApplications: elsewhere } : {}), manufacturer: app.manufacturer, manufacturerName: app.manufacturerName,
      mask, version: catalogueVersion(app.version), name: app.name,
      orderNumber: (own ?? others.find(searchable) ?? others[0]).orderNumber, orderNumbers, catalogueEntries: app.entries.length,
    };
    if (shared.length) row.sameOrderAndVersion = shared;
    if (!own) row.noOwnOrderNumber = true;
    if (app.second.size) row.secondProgram = [...app.second].sort(byText).map((id) => ({ application: id, programType: secondType.get(id) ?? null }));
    if (app.entries.some((e) => e.SecurityInfo !== 0)) row.secure = true;
    if (app.entries.some((e) => e.NoDownloadWithoutPlugin)) row.pluginRequired = true;
    if (app.entries.some((e) => e.RequiresExternalSoftware)) row.externalSoftware = true;
    if (app.entries.some((e) => e.DownloadInfoIncomplete)) row.downloadInfoIncomplete = true;
    rows.push(row);
    catalogueIdsOf.set(row, app.catalogueIds);
  }
  const rowsByManufacturer: Record<string, Record<string, number>> = {};
  for (const r of rows) {
    const k = `${r.manufacturer} ${r.manufacturerName}`;
    rowsByManufacturer[k] ??= {};
    rowsByManufacturer[k][r.mask] = (rowsByManufacturer[k][r.mask] ?? 0) + 1;
  }
  const refusedApplications = refused.filter((r) => r.kind === "application");
  const list: CatalogueList = {
    format: LIST_FORMAT,
    source: { ...f.source, market: marketName, indexFiles: f.indexes.length, masks },
    counts: {
      indexEntries, marketEntries, withoutApplication, refusedEntries: refused.filter((r) => r.kind === "entry").length,
      applications: maskOf.size + unloaded.length + refusedApplications.length, loaded: maskOf.size, unloaded: unloaded.length, refusedApplications: refusedApplications.length,
      byMask, rows: rows.length,
      rowsByManufacturer, sameOrderAndVersion: rows.filter((r) => r.sameOrderAndVersion).length,
      marketIdsWithoutEntry, secondApplications: [...secondType.values()].filter((t) => t === "ApplicationProgram").length,
    },
    rows, unloaded, refused,
  };
  if (bussard) {
    // Every program of the market by the index's id: an application with its mask, or why it was refused (neither:
    // not loaded), or a second program beside an application.
    const offered = new Map<string, Offered>();
    for (const app of apps.values()) {
      const why = refusedApplications.find((r) => r.entry === app.id)?.why;
      for (const id of app.catalogueIds) offered.set(id, maskOf.has(app.id) ? { mask: maskOf.get(app.id)! } : why ? { refused: why } : {});
      for (const id of app.catalogueSecond) if (!offered.has(id)) offered.set(id, { secondOf: app.id });
    }
    for (const r of refusedApplications) if (!offered.has(r.entry)) offered.set(r.entry, { refused: r.why });
    list.bussard = compareBussard(rows.map((row) => ({ row, ids: catalogueIdsOf.get(row)! })), offered, bussard, masks);
  }
  return list;
}

// ---- bussard's manifest, compared ----

export interface BussardManifest { generated: string; apps: Record<string, { mask: string; manufacturer: string; outcome: string }> }

// An application without its version and fingerprint: M-0002_A-4758-O0007 for M-0002_A-4758-11-0055-O0007.
const applicationKey = (id: string) => id.replace(/-[0-9A-F]{2}-[0-9A-F]{4}(?=(-O[0-9A-F]+)?$)/, "");

// Ids by their application key.
function byKey(ids: Iterable<string>): Map<string, string[]> {
  const out = new Map<string, string[]>();
  for (const id of ids) out.set(applicationKey(id), [...(out.get(applicationKey(id)) ?? []), id]);
  return out;
}

// A program the market offers: an application with its mask or why its product data was refused (neither: not
// loaded), or a second program beside an application.
interface Offered { mask?: string; refused?: string; secondOf?: string }

// bussard's applications at `masks` against the rows (each with the index's ids of it), both ways.
function compareBussard(rows: { row: Row; ids: string[] }[], offered: Map<string, Offered>, manifest: BussardManifest, masks: string[]): BussardCheck {
  const theirs = new Map(Object.entries(manifest.apps).filter(([, a]) => masks.includes(a.mask)));
  const ours = new Map(rows.flatMap(({ row, ids }) => ids.map((id) => [id, row] as const)));
  const offeredByKey = byKey(offered.keys()), theirsByKey = byKey(Object.keys(manifest.apps));
  const otherVersions = (index: Map<string, string[]>, id: string) => (index.get(applicationKey(id)) ?? []).filter((x) => x !== id).sort(byText);
  const theirManufacturers = new Set(Object.values(manifest.apps).map((a) => a.manufacturer));
  const theirsNotOurs: BussardDifference[] = [], oursNotTheirs: BussardDifference[] = [], maskDiffers: BussardCheck["maskDiffers"] = [];
  for (const [id, a] of theirs) {
    const row = ours.get(id);
    if (row) { if (row.mask !== a.mask) maskDiffers.push({ application: id, ours: row.mask, theirs: a.mask }); continue; }
    const d: BussardDifference = { application: id, mask: a.mask, reason: "", outcome: a.outcome };
    const here = offered.get(id);
    if (here) {
      if (here.secondOf) { d.reason = "in the catalogue as the second program beside another application"; d.detail = here.secondOf; }
      else if (here.mask) { d.reason = "in the catalogue at another mask by its product data here"; d.detail = here.mask; }
      else if (here.refused) { d.reason = "in the catalogue, its product data refused here"; d.detail = here.refused; }
      else d.reason = "in the catalogue, its product data not loaded here";
    } else {
      const others = otherVersions(offeredByKey, id);
      if (others.length) { d.reason = "not in the catalogue; another version of its application is"; d.detail = others.join(", "); }
      else d.reason = "not in the catalogue for this market";
    }
    theirsNotOurs.push(d);
  }
  for (const { row: r, ids } of rows) {
    if (ids.some((id) => theirs.has(id))) continue;
    const id = ids[0];
    const d: BussardDifference = { application: id, mask: r.mask, reason: "" };
    const other = ids.map((x) => manifest.apps[x]).find(Boolean);
    const versions = [...new Set(ids.flatMap((x) => otherVersions(theirsByKey, x)))].filter((v) => !ids.includes(v)).sort(byText);
    if (other) { d.reason = "in bussard's manifest at another mask"; d.detail = other.mask; }
    else if (versions.length) { d.reason = "bussard holds another version of its application"; d.detail = versions.map((v) => `${v} (${manifest.apps[v].outcome})`).join(", "); }
    else d.reason = theirManufacturers.has(r.manufacturer) ? "not in bussard's manifest; its manufacturer is" : "not in bussard's manifest, nor its manufacturer";
    oursNotTheirs.push(d);
  }
  const both = [...theirs.keys()].filter((id) => ours.has(id)).length;
  return { generated: manifest.generated, theirs: theirs.size, ours: rows.length, both, theirsNotOurs, oursNotTheirs, maskDiffers };
}

// ---- Markdown ----

const reasonCounts = (ds: BussardDifference[]) => {
  const c = new Map<string, number>();
  for (const d of ds) c.set(d.reason, (c.get(d.reason) ?? 0) + 1);
  return [...c].sort((a, b) => b[1] - a[1]);
};

export function markdown(list: CatalogueList): string {
  const c = list.counts, s = list.source;
  const masks = Object.keys(c.byMask).sort(byText);
  const lines = [
    GENERATED_START,
    "",
    "## How the list was made",
    "",
    `- ETS: ${s.ets}, licence ${s.licence}; market ${s.market}; catalogue index of ${s.catalogueDate} (${s.indexFiles} manufacturer files), fetched ${s.fetched}.`,
    "- Entries: ETS's catalogue index on the bench host; a mask: the `MaskVersion` of the application in ETS's product store, loaded through the catalogue's Herunterladen (`tools/ets-driver.ts catalogue-download`). No mask is taken from a name.",
    `- Rows: one per application at mask ${s.masks.join(", ")}; regenerate with \`tools/ets-catalogue.ts fetch\` and \`list\`.`,
    "",
    "## Counts",
    "",
    "| | |",
    "|---|---:|",
    `| index entries | ${c.indexEntries} |`,
    `| offered in ${s.market} | ${c.marketEntries} |`,
    `| of them without an application | ${c.withoutApplication} |`,
    `| of them refused (id, identifier, fingerprint or manufacturer disagree) | ${c.refusedEntries} |`,
    `| applications | ${c.applications} |`,
    `| with product data loaded (mask known) | ${c.loaded} |`,
    `| not loaded (no mask, no row) | ${c.unloaded} |`,
    `| refused (the product data does not fit) | ${c.refusedApplications} |`,
    `| **rows (${s.masks.join(", ")})** | **${c.rows}** |`,
    `| rows sharing an order number and version with another application | ${c.sameOrderAndVersion} |`,
    `| of them without an order number of their own | ${list.rows.filter((r) => r.noOwnOrderNumber).length} |`,
    `| second programs that are applications (no row of their own) | ${c.secondApplications} |`,
    `| catalogue ids of the market naming no index entry | ${c.marketIdsWithoutEntry} |`,
    "",
    "### Applications per mask (product data)",
    "",
    "| mask | applications | row |",
    "|---|---:|---|",
    ...masks.map((m) => `| ${m} | ${c.byMask[m]} | ${s.masks.includes(m) ? "yes" : ""} |`),
    "",
    "### Rows per manufacturer",
    "",
    `| manufacturer | ${s.masks.join(" | ")} | all |`,
    `|---|${s.masks.map(() => "---:").join("|")}|---:|`,
    ...Object.entries(c.rowsByManufacturer).sort((a, b) => byText(a[0], b[0]))
      .map(([m, n]) => `| ${m} | ${s.masks.map((k) => n[k] ?? 0).join(" | ")} | ${Object.values(n).reduce((x, y) => x + y, 0)} |`),
    `| **all** | ${s.masks.map((k) => list.rows.filter((r) => r.mask === k).length).join(" | ")} | ${c.rows} |`,
    "",
    "### Flags on rows",
    "",
    `- secure-capable product: ${list.rows.filter((r) => r.secure).length}`,
    `- download needs a plug-in: ${list.rows.filter((r) => r.pluginRequired).length}`,
    `- needs external software: ${list.rows.filter((r) => r.externalSoftware).length}`,
    `- download info incomplete: ${list.rows.filter((r) => r.downloadInfoIncomplete).length}`,
    ...Object.entries(Object.groupBy(list.rows.flatMap((r) => r.secondProgram ?? []), (p) => p.programType ?? "not loaded"))
      .sort((a, b) => byText(a[0], b[0])).map(([t, ps]) => `- a second program beside the application, ${t}: ${ps?.length ?? 0}`),
  ];
  if (list.refused.length) lines.push("", "### Refused", "", ...list.refused.map((r) => `- ${r.kind} \`${r.entry}\`: ${r.why}`));
  const b = list.bussard;
  if (b) {
    lines.push(
      "", "## bussard's manifest, compared", "",
      `bussard's manifest of ${b.generated}: ${b.theirs} applications at these masks, ours ${b.ours}, both ${b.both}; mask differs on ${b.maskDiffers.length}.`,
      "", `In bussard's, not here (${b.theirsNotOurs.length}):`, "",
      ...reasonCounts(b.theirsNotOurs).map(([k, n]) => `- ${n}: ${k}`),
      "", `Here, not in bussard's (${b.oursNotTheirs.length}):`, "",
      ...reasonCounts(b.oursNotTheirs).map(([k, n]) => `- ${n}: ${k}`),
    );
    if (b.maskDiffers.length) lines.push("", "Mask differs:", "", ...b.maskDiffers.map((d) => `- \`${d.application}\`: here ${d.ours}, bussard ${d.theirs}`));
  }
  lines.push("", GENERATED_END, "");
  return lines.join("\n");
}

// The generated part put into `old` (an existing file's text) between its markers, or below its text.
// The markers must stand once each, in order; a file without them gets the generated part below its text.
export function withGenerated(old: string | null, generated: string): string {
  if (!old) return `# ETS online catalogue: the sweep's list\n\n${generated}`;
  const count = (m: string) => old.split(m).length - 1;
  const [starts, ends] = [count(GENERATED_START), count(GENERATED_END)];
  if (starts === 0 && ends === 0) return `${old.trimEnd()}\n\n${generated}`;
  const a = old.indexOf(GENERATED_START), b = old.indexOf(GENERATED_END);
  if (starts !== 1 || ends !== 1 || b < a) throw new Error(`the Markdown file holds its markers ${starts} and ${ends} times${b < a ? ", the end first" : ""}: not rewritten`);
  return old.slice(0, a) + generated.trimEnd() + old.slice(b + GENERATED_END.length);
}

// ---- command line ----

function main(): number {
  const [cmd, ...rest] = process.argv.slice(2);
  const opts = new Map<string, string>(), args: string[] = [];
  for (let i = 0; i < rest.length; i++) {
    if (!rest[i].startsWith("--")) { args.push(rest[i]); continue; }
    const [name, value] = [rest[i].slice(2), rest[++i]];
    if (value === undefined || value.startsWith("--")) throw new Error(`--${name} takes a value`);
    if (opts.has(name)) throw new Error(`--${name} is given twice`);
    opts.set(name, value);
  }
  const usage = "usage: bun run tools/ets-catalogue.ts fetch [--out <dir>] | list <fetched dir> --json <file> --md <file> [--market Germany] [--masks 07B0,0701,0705] [--bussard <manifest.json>]";
  if (cmd === "fetch") {
    if (args.length || [...opts.keys()].some((k) => k !== "out")) throw new Error(usage);
    fetchCatalogue(opts.get("out") ?? join(tmpdir(), "ets-catalogue"));
    return 0;
  }
  if (cmd === "list") {
    const jsonOut = opts.get("json"), mdOut = opts.get("md");
    if (args.length !== 1 || !jsonOut || !mdOut || [...opts.keys()].some((k) => !["json", "md", "market", "masks", "bussard"].includes(k))) throw new Error(usage);
    const masks = [...new Set(opts.get("masks")?.split(",") ?? SWEEP_MASKS)];
    if (masks.some((m) => !/^[0-9A-F]{4}$/.test(m))) throw new Error(`--masks takes masks as four upper-case hex digits (07B0), not ${opts.get("masks")}`);
    const f = readFetched(args[0]);
    const bussard = opts.get("bussard");
    const list = catalogueList(f, opts.get("market") ?? "Germany", masks,
      bussard ? json<BussardManifest>(readFileSync(bussard, "utf8")) : undefined);
    writeFileSync(jsonOut, `${JSON.stringify(list, null, 1)}\n`);
    writeFileSync(mdOut, withGenerated(existsSync(mdOut) && statSync(mdOut).size ? readFileSync(mdOut, "utf8") : null, markdown(list)));
    const c = list.counts;
    console.log(`${c.rows} rows (${list.source.masks.map((m) => `${m} ${list.rows.filter((r) => r.mask === m).length}`).join(", ")}); ${c.applications} applications offered, ${c.unloaded} not loaded, ${list.refused.length} refused`);
    return c.unloaded || list.refused.length ? 1 : 0;
  }
  throw new Error(usage);
}

if (import.meta.main) {
  try { process.exit(main()); }
  catch (e) { console.error(`ets-catalogue: ${e instanceof Error ? e.message : String(e)}`); process.exit(2); }
}
